def reply(kind: str, lang: str) -> str:
    table = REPLIES[kind]
    return table.get(lang) or table[languages.DEFAULT]


def done(card: dict, lang: str) -> str:
    """Tell the caller a booking change went through, with its reference."""
    action = card.get("action")
    ref = card.get("new_ref") or card.get("ref") or ""
    table = DONE.get(lang) or DONE[languages.DEFAULT]
    text = table.get(action) or table["other"]
    return text + (f" Reference {ref}." if ref and action != "cancel" else "")


def buttons(lang: str) -> dict:
    return BUTTONS.get(lang) or BUTTONS[languages.DEFAULT]
